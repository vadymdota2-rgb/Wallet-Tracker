/**
 * Как часто приложение спрашивает сервер — отдельно от сети и хранилища,
 * чтобы правила проверяли тесты (tests/pace.test.ts).
 *
 * Норма nginx — 120 запросов в минуту на человека (плюс запас 30). Раньше
 * при неполной выгрузке («справочник ещё собирается») приложение
 * переспрашивало её каждые 2,5 секунды и после каждого ответа заново
 * запускало всю подгрузку — около 60 запросов за круг. Два круга в минуту
 * уже больше нормы: у одного телефона выходило 254 запроса за минуту, и
 * nginx отказывал всем экранам подряд (ETF, доминация, монеты, сделки).
 */

/** Первый повтор неполной выгрузки — быстро: обычно её дособирают за секунды. */
export const SOON_DELAY = 2_500;
/** Дальше — реже, до 30 секунд: что не собралось за минуту, не соберётся и
 *  от частых вопросов, а каждая выгрузка — запрос из той же нормы. */
export const SOON_MAX = 30_000;
/** Следующая пауза при неполной выгрузке: вдвое, но не больше SOON_MAX. */
export const nextSoon = (delay: number): number => Math.min(SOON_MAX, delay * 2);

/** Подгрузка всего подряд — не чаще раза в минуту, сколько бы ни было выгрузок. */
export const PREFETCH_GAP = 60_000;

/** Пропускает не чаще раза в gap мс: true — можно, и время запомнено. */
export function gate(gap: number): (now: number) => boolean {
  let last = -Infinity;
  return (now) => {
    if (now - last < gap) return false;
    last = now;
    return true;
  };
}

/**
 * Очередь заданий, не больше parallel разом. stop() — сервер сказал «слишком
 * часто» (429): остальное не шлём, иначе каждый новый отказ держал бы норму
 * заполненной, и подгрузка мешала бы экрану, который человек открыл сам.
 */
export async function drain(jobs: readonly (() => Promise<unknown>)[], parallel: number,
  stop: () => boolean = () => false): Promise<void> {
  let next = 0;
  const worker = async () => {
    while (next < jobs.length && !stop()) {
      const job = jobs[next++];
      try {
        if (job) await job();
      } catch {
        // Подгрузка — не обязательство: не вышло — экран сходит сам.
      }
    }
  };
  await Promise.all(Array.from({ length: Math.min(parallel, jobs.length) }, worker));
}
